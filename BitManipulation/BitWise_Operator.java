package BitManipulation;

public class BitWise_Operator {

    public static void main(String[] args) {

        System.out.println(5 & 6);
        System.out.println(5 | 6);
        System.out.println(5 ^ 6);
        System.out.println(~0);
        System.out.println(1 << 2);
        System.out.println(6 >> 1);
    }
}